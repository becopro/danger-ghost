// Gera js/legacy/wallet.bundle.js a partir do módulo de carteira do repo ghostgames-onchain.
//
// Uso (na pasta "danger ghost"):
//   node tools/build-legacy-wallet.js
// Pasta do ghostgames-onchain: variável ONCHAIN_DIR, ou ../../ghostgames-onchain por padrão.
// Usa o esbuild e as dependências já instaladas lá (npm install no ghostgames-onchain).
// Rode de novo sempre que src/wallet.js mudar lá, e confira o diff do bundle antes do commit.
const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
const ONCHAIN_DIR = path.resolve(process.env.ONCHAIN_DIR || path.join(ROOT, '..', '..', 'ghostgames-onchain'));
const WALLET_SRC = path.join(ONCHAIN_DIR, 'src', 'wallet.js');
const NODE_MODULES = path.join(ONCHAIN_DIR, 'node_modules');
const OUT_FILE = path.join(ROOT, 'js', 'legacy', 'wallet.bundle.js');

if (!fs.existsSync(WALLET_SRC) || !fs.existsSync(path.join(NODE_MODULES, 'esbuild'))) {
    console.error('ghostgames-onchain não encontrado (ou sem npm install) em: ' + ONCHAIN_DIR);
    process.exit(1);
}

const esbuild = require(path.join(NODE_MODULES, 'esbuild'));

esbuild.build({
    entryPoints: [path.join(__dirname, 'legacy-wallet-entry.js')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: true,
    legalComments: 'eof',
    alias: { 'gg-onchain-wallet': WALLET_SRC },
    nodePaths: [NODE_MODULES],
    outfile: OUT_FILE,
    banner: { js: '/* Ghost Games Legacy wallet bundle. Generated by tools/build-legacy-wallet.js from ghostgames-onchain/src/wallet.js. Do not edit by hand. */' },
}).then(() => {
    console.log('OK: ' + path.relative(ROOT, OUT_FILE) + ' (' + fs.statSync(OUT_FILE).size + ' bytes)');
}).catch(() => process.exit(1));
